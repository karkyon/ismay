import { type PiiClassification } from "@/lib/pem/coreTypes";

/**
 * V5-M1-B6 PII分類器。
 * 出典: `ISMAY_統合正本仕様書_v5_0.md` §3(SourceAnchor「原文位置検証、PII分類」)、
 * §19.5「推論禁止」。
 *
 * [設計方針・最重要] §19.5は「人格、道徳、知能、能力の断定」「医療、精神、
 * 身体健康状態、障害、依存症」「宗教、政治思想、性的指向」「雇用適性、労働能力、
 * 信用・返済能力」「家族関係の断定」の推定・断定を明確に禁止している。この
 * ファイルは、そうした属性を**推論しない**。連絡先情報(メールアドレス・
 * 電話番号)という、正規表現で機械的・客観的に検出できる形式的パターンのみを
 * 対象とする(「この文章はセンシティブそうだ」という主観的判断は一切行わない)。
 *
 * [scope外の明記] 氏名・会社名等の固有表現検出は信頼できる形態素解析/NER
 * (固有表現抽出)を要し、このリポジトリには実装が無い。正規表現で「それらしい
 * 単語」を推測するのは誤検出(false positive/negative)のリスクが高く、
 * 「想像で分類しない」という既存方針に反するため、このv1では行わない。
 * §19.4のPII仮名化Vault(tenant別token置換)も「将来候補・設計未完了のため
 * 実装着手しない」と明記されている別機能であり、このGateのscope外。
 *
 * [判定levels] PII_CLASSIFICATIONS=NONE/LOW/MEDIUM/HIGHのうち、このv1が実際に
 * 判定できるのはNONE/HIGHの2値のみ(客観的パターンが「有る」か「無い」かの
 * 二値判定しかできないため)。LOW/MEDIUMは「連絡先ではないが間接的に個人を
 * 特定しうる情報(住所の一部、生年月日等)」に相当すると考えられるが、
 * この判定には現状信頼できる検出手段が無いため、値としては予約するが
 * このv1のロジックからは返さない(想像で中間段階を作らない)。
 */

/**
 * 日本の携帯電話番号(090/080/070)・固定電話番号(市外局番)の一般的な表記
 * (ハイフン区切り)にマッチする。国際表記(+81)も含む。
 * [設計判断・2026-08-30是正] 当初はハイフンを任意(`[-\s]?`)としていたが、
 * 「1000-2000円」のような単なる数値範囲を誤って電話番号と判定してしまう
 * false positiveが実際にpure testで発覚した。区切りのハイフンを必須にし、
 * 前後を数字で挟まれていないこと(`(?<!\d)`/`(?!\d)`)を要求することで、
 * より長い数字列の一部分だけを切り出して誤マッチすることを防ぐ。
 * [既知の限界] ハイフン無し表記(例: 09012345678)は検出しない
 * (誤検出を避けるための保守的判断。PII検出の見逃しより、無関係な数値列を
 * HIGHと誤判定する方が実害が大きいと判断した)。
 */
const PHONE_PATTERN = /(?<!\d)(?:\+81-?\d{1,4}-\d{2,4}-\d{3,4}|0\d{1,4}-\d{2,4}-\d{3,4})(?!\d)/;

/** RFC 5322の完全準拠ではなく、実務上十分な簡易メールアドレスpattern。 */
const EMAIL_PATTERN = /[a-zA-Z0-9][a-zA-Z0-9._%+-]*@[a-zA-Z0-9][a-zA-Z0-9.-]*\.[a-zA-Z]{2,}/;

/**
 * 抜粋文字列(SourceAnchorのexcerpt相当)を分類する。
 * メールアドレス・電話番号のいずれかのpatternに一致すればHIGH、
 * 一致しなければNONEを返す。
 */
export function classifyPii(excerpt: string): PiiClassification {
  if (EMAIL_PATTERN.test(excerpt) || PHONE_PATTERN.test(excerpt)) {
    return "HIGH";
  }
  return "NONE";
}
