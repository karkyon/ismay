class PreflightError(Exception):
    pass


def log(msg: str) -> None:
    print(msg)


def run_git(args: list[str]) -> tuple[int, str, str]:
    result = subprocess.run(["git", *args], cwd=REPO_ROOT, capture_output=True, text=True)
    return result.returncode, result.stdout.strip(), result.stderr.strip()


# =====================================================================
# STEP 1: Preflight(何も書き換えない。1つでも不成立なら例外を投げて終了)
# =====================================================================

def preflight() -> dict:
    findings: dict = {}

    # 1. 期待ファイルの存在確認(=リポジトリルートで実行されているか)
    if not SCHEMA_PATH.exists():
        raise PreflightError(
            f"schema.prismaが見つかりません: {SCHEMA_PATH}\n"
            "既存ISMAYリポジトリのルートで実行してください(新規cloneは不要です)。"
        )
    if not PACKAGE_JSON_PATH.exists():
        raise PreflightError(f"package.jsonが見つかりません: {PACKAGE_JSON_PATH}")

    # 2. git status --short をリポジトリ全体に対して実行(app/限定にしない)。
    #    ただし、このパッチ自身(リポジトリルートに置かれた未追跡ファイル)は
    #    「無視してよい未コミット変更」として明示的に除外する
    #    (パッチはリポジトリのルートへ置いて実行する運用のため、自分自身が
    #    未追跡であることは「作業ツリーが汚れている」ことを意味しない)。
    rc, out, err = run_git(["status", "--short"])
    if rc != 0:
        raise PreflightError(f"`git status --short` が失敗しました: {err}")
    self_name = Path(__file__).resolve().name
    other_lines = [
        line for line in out.splitlines()
        if line.strip() and Path(line[3:].strip()).name != self_name
    ]
    if other_lines:
        raise PreflightError(
            "作業ツリーに未コミット変更があります(リポジトリ全体、"
            "このパッチ自身のファイルを除く)。cleanな状態で再実行してください:\n"
            + "\n".join(other_lines)
        )

    # 3. HEAD確認
    rc, head, err = run_git(["rev-parse", "HEAD"])
    if rc != 0:
        raise PreflightError(f"`git rev-parse HEAD` が失敗しました: {err}")
    if head != EXPECTED_HEAD:
        raise PreflightError(
            "想定HEADと実HEADが一致しません。reset等は行いません。事実のみ報告します。\n"
            f"  想定HEAD: {EXPECTED_HEAD}\n"
            f"  実際HEAD: {head}\n"
            "差分を確認し、正本への影響を評価してから再実行してください。"
        )
    findings["head"] = head

    # 4. origin/main確認(取得できる場合のみ。fetchはしない=ネットワークを勝手に叩かない)
    rc, origin_main, err = run_git(["rev-parse", "origin/main"])
    if rc == 0:
        findings["origin_main"] = origin_main
        if origin_main != head:
            raise PreflightError(
                "HEADとorigin/mainが一致しません。reset/pullは行いません。事実のみ報告します。\n"
                f"  HEAD:        {head}\n"
                f"  origin/main: {origin_main}\n"
                "`git fetch origin` を実行して差分を確認してから、"
                "続行するか判断してください。"
            )
    else:
        findings["origin_main"] = None
        log("[NOTE] origin/main を解決できませんでした(fetch未実行またはremote未設定の可能性)。"
            "HEAD一致のみで続行します。")

    # 5. 二重適用検出: schema.prisma に新モデルが無いこと
    schema_text = SCHEMA_PATH.read_text(encoding="utf-8")
    for name in NEW_MODEL_NAMES:
        pattern = re.compile(r"^model " + re.escape(name) + r" \{", re.MULTILINE)
        if pattern.search(schema_text):
            raise PreflightError(f"schema.prisma に model {name} が既に存在します(二重適用)。")

    # 6. anchorが期待どおり1回だけ存在すること
    anchors = [
        ("Domain", DOMAIN_OLD),
        ("Workspace", WORKSPACE_OLD),
        ("User", USER_OLD),
        ("Responsibility", RESPONSIBILITY_OLD),
    ]
    for label, anchor in anchors:
        count = schema_text.count(anchor)
        if count != 1:
            raise PreflightError(
                f"{label} 用anchor文字列が {count} 件見つかりました(1件を期待)。"
                "schema.prismaが想定と異なる可能性があります。手動確認してください。"
            )
    findings["schema_text"] = schema_text

    # 7. migrationディレクトリ・出力ファイル・package scriptが未追加であること
    if NEW_MIGRATION_DIR.exists():
        raise PreflightError(f"migrationディレクトリが既に存在します: {NEW_MIGRATION_DIR}")
    if CORE_TYPES_PATH.exists():
        raise PreflightError(f"既に存在します: {CORE_TYPES_PATH}")
    if CORE_TEST_PATH.exists():
        raise PreflightError(f"既に存在します: {CORE_TEST_PATH}")

    package_text = PACKAGE_JSON_PATH.read_text(encoding="utf-8")
    try:
        package_json = json.loads(package_text)
    except json.JSONDecodeError as e:
        raise PreflightError(f"package.jsonのJSON parseに失敗しました: {e}")
    scripts = package_json.get("scripts", {})
    if "test:project-context" in scripts:
        raise PreflightError("package.json に test:project-context が既に存在します(二重適用)。")
    if '"test:pem":' not in package_text:
        raise PreflightError("package.json に test:pem anchorが見つかりません。想定外の構造です。")
    if package_text.count('"test:pem":') != 1:
        raise PreflightError("package.json の test:pem anchorが複数件あります。想定外です。")
    findings["package_text"] = package_text

    # 8. 埋め込みpayloadの非空・model名重複なし確認
    if not CORE_TYPES_TS.strip():
        raise PreflightError("埋め込みcoreTypes.tsが空です。")
    if not CORE_TEST_TS.strip():
        raise PreflightError("埋め込みcoreInvariants.test.tsが空です。")
    if not MIGRATION_SQL.strip():
        raise PreflightError("埋め込みmigration.sqlが空です。")
    found_models = re.findall(r"^model (\w+) \{", SCHEMA_BLOCK_PRISMA, re.MULTILINE)
    if sorted(found_models) != sorted(NEW_MODEL_NAMES):
        raise PreflightError(
            f"埋め込みschema modelブロックのmodel名が期待と一致しません。"
            f"期待: {sorted(NEW_MODEL_NAMES)} / 実際: {sorted(found_models)}"
        )
    if len(found_models) != len(set(found_models)):
        raise PreflightError("埋め込みschema modelブロック内でmodel名が重複しています。")

    # 9. brace対応確認(適用後の全文で検算する。ここでは埋め込みブロック単体をチェック)
    if SCHEMA_BLOCK_PRISMA.count("{") != SCHEMA_BLOCK_PRISMA.count("}"):
        raise PreflightError("埋め込みschema modelブロックの中括弧が対応していません。")

    log("[OK] preflight: 全項目クリア(実ファイルはまだ一切変更していません)")
    return findings


# =====================================================================
# STEP 2: 全変更をメモリ上で組み立て、静的検証する
# =====================================================================

def build_new_contents(findings: dict) -> dict:
    schema_text = findings["schema_text"]
    package_text = findings["package_text"]

    new_schema_text = schema_text.replace(DOMAIN_OLD, DOMAIN_NEW, 1)
    new_schema_text = new_schema_text.replace(WORKSPACE_OLD, WORKSPACE_NEW, 1)
    new_schema_text = new_schema_text.replace(USER_OLD, USER_NEW, 1)
    new_schema_text = new_schema_text.replace(RESPONSIBILITY_OLD, RESPONSIBILITY_NEW, 1)
    new_schema_text = new_schema_text + SCHEMA_BLOCK_PRISMA

    # 静的検証: brace対応(適用後の全文)
    if new_schema_text.count("{") != new_schema_text.count("}"):
        raise PreflightError("適用後のschema.prisma全文で中括弧が対応していません。書き込みを中止します。")

    # 静的検証: 6モデルが正確に1回ずつ存在する
    for name in NEW_MODEL_NAMES:
        pattern = re.compile(r"^model " + re.escape(name) + r" \{", re.MULTILINE)
        matches = pattern.findall(new_schema_text)
        if len(matches) != 1:
            raise PreflightError(f"適用後のschema.prismaで model {name} が {len(matches)} 件です(1件を期待)。")

    # package.json: test:pem行の直前にtest:project-contextを挿入し、JSONとして妥当か検証
    idx = package_text.index('"test:pem":')
    new_package_text = (
        package_text[:idx] + TEST_SCRIPT_LINE + "\n    " + package_text[idx:]
    )
    try:
        parsed = json.loads(new_package_text)
    except json.JSONDecodeError as e:
        raise PreflightError(f"適用後のpackage.jsonがJSONとして不正です: {e}")
    if parsed.get("scripts", {}).get("test:project-context") != (
        "tsx src/lib/projectContext/__tests__/coreInvariants.test.ts"
    ):
        raise PreflightError("適用後のpackage.jsonでtest:project-contextの値が想定と異なります。")

    log("[OK] メモリ上での組み立てと静的検証が完了しました(実ファイルはまだ一切変更していません)。")
    return {
        "schema.prisma": new_schema_text,
        "package.json": new_package_text,
        "coreTypes.ts": CORE_TYPES_TS,
        "coreInvariants.test.ts": CORE_TEST_TS,
        "migration.sql": MIGRATION_SQL,
    }


# =====================================================================
# STEP 3: atomic適用(一時ファイル→os.replace。途中失敗時は全ロールバック)
# =====================================================================

def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(dir=str(path.parent), prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp_path, path)
    except BaseException:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)
        raise


def apply(new_contents: dict) -> list[str]:
    backups: dict[Path, Path] = {}
    created_files: list[Path] = []
    created_dirs: list[Path] = []
    changed: list[str] = []

    try:
        # 既存ファイル(schema.prisma / package.json)をbackupしてからatomic置換。
        for path, key in [(SCHEMA_PATH, "schema.prisma"), (PACKAGE_JSON_PATH, "package.json")]:
            backup_path = path.with_suffix(path.suffix + ".m1a1.bak")
            shutil.copy2(path, backup_path)
            backups[path] = backup_path
            atomic_write(path, new_contents[key])
            changed.append(str(path.relative_to(REPO_ROOT)))

        # 新規ファイル(存在しなかったもの。失敗時は削除する)。
        for path, key in [
            (CORE_TYPES_PATH, "coreTypes.ts"),
            (CORE_TEST_PATH, "coreInvariants.test.ts"),
            (NEW_MIGRATION_SQL_PATH, "migration.sql"),
        ]:
            if not path.parent.exists():
                created_dirs.append(path.parent)
            path.parent.mkdir(parents=True, exist_ok=True)
            atomic_write(path, new_contents[key])
            created_files.append(path)
            changed.append(str(path.relative_to(REPO_ROOT)))

    except BaseException as e:
        log(f"[FAIL] 適用中にエラーが発生しました: {e}")
        log("[ROLLBACK] 作成済みの新規ファイルを削除し、既存ファイルをbackupから復元します。")
        for path in created_files:
            if path.exists():
                path.unlink()
        for d in created_dirs:
            try:
                if d.exists() and not any(d.iterdir()):
                    d.rmdir()
            except OSError:
                pass
        for path, backup_path in backups.items():
            if backup_path.exists():
                shutil.copy2(backup_path, path)
                backup_path.unlink()
        raise

    # 成功: backupを削除。
    for backup_path in backups.values():
        if backup_path.exists():
            backup_path.unlink()

    return changed


def main() -> None:
    log("V5-M1-A1 Project Context DB・Domain基盤 適用パッチ")
    log(f"  リポジトリルート(想定): {REPO_ROOT}")

    try:
        findings = preflight()
        new_contents = build_new_contents(findings)
        changed = apply(new_contents)
    except PreflightError as e:
        log(f"[BLOCKED] {e}")
        log("何もファイルを変更していません。")
        sys.exit(1)
